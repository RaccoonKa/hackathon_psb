def serialize_result(result, query: str) -> dict:
    """Сериализует AgentResult в JSON-совместимый dict для сохранения в файл."""
    return {
        "query": query,
        "final_answer": result.final_answer,
        "intent": result.intent,
        "refused": result.refused,
        "refusal_reason": result.refusal_reason,
        "confidence": result.confidence,
        "assumptions": list(result.assumptions or []),
        "missing_info": list(result.missing_info or []),
        "degradation_reasons": list(result.degradation_reasons or []),
        "used_history": result.used_history,
        "sources": {
            sid: {
                "document_title": meta.get("document_title"),
                "document_id": meta.get("document_id"),
                "version_id": meta.get("version_id"),
                "chunk_id": meta.get("chunk_id"),
                "provision_id": meta.get("provision_id"),
                "structure_path": list(meta.get("structure_path") or []),
                "score": meta.get("score"),
                "effective_from": meta.get("effective_from"),
                "effective_to": meta.get("effective_to"),
                "amends_document_id": meta.get("amends_document_id"),
            }
            for sid, meta in (result.sources or {}).items()
        },
        "trace": [asdict(step) for step in result.trace],
    }


def exec(query: str) -> dict:
    result = run_agent(query)
    answer = replace_source_tags(result.final_answer, result.sources or {})

    print("\n" + "=" * 60)
    if NEED_INTENT:
        print(f"🎯 ИНТЕНТ: {result.intent}")
        print(f"🚫 ОТКАЗ (Refused): {result.refused}")
        print("\n💡 ОТВЕТ:")
    print(answer) 

    if NEED_SOURCES:
        print("\n📚 ИСТОЧНИКИ:")
        if result.sources:
            for source_id, meta in result.sources.items():
                print(f"  [{source_id}] {meta.get('document_title', 'N/A')}")
                print(f"        Путь: {' -> '.join(meta.get('structure_path') or [])}")
                print(f"        Score: {meta.get('score', 0):.3f} | Chunk: {meta.get('chunk_id', 'N/A')}")
        else:
            print("  Нет релевантных источников.")

    if NEED_TRACE:
        print("\n🔍 ПОЛНЫЙ ТРЕЙС (Trace):")
        print(json.dumps([asdict(step) for step in result.trace], indent=2, ensure_ascii=False))

    print("=" * 60)

    return serialize_result(result, query)


def format_result_for_file(r: dict, index: int, total: int) -> str:
    """Компактный формат для файла: запрос → ответ → источники → интент/отказ → полный трейс."""
    lines: list[str] = []
    sep = "=" * 70
    lines.append(f"\n{sep}")
    lines.append(f"ЗАПРОС {index}/{total}")
    lines.append(f"{sep}")
    lines.append(f"ВОПРОС: {r['query']}")
    lines.append("")
    lines.append("ОТВЕТ:")
    lines.append(r["final_answer"] or "(пустой ответ)")
    lines.append("")
    lines.append("ИСТОЧНИКИ:")
    if r["sources"]:
        for sid, meta in r["sources"].items():
            path = " -> ".join(meta.get("structure_path") or []) or "(пусто)"
            lines.append(
                f"  [{sid}] {meta.get('document_title', 'N/A')} | "
                f"{path} | score={meta.get('score')} | chunk={meta.get('chunk_id')}"
            )
    else:
        lines.append("  (нет источников)")
    lines.append("")
    lines.append(f"ИНТЕНТ: {r['intent']}")
    lines.append(f"ОТКАЗ: {r['refused']} | Причина: {r['refusal_reason']}")
    lines.append(f"УВЕРЕННОСТЬ: {r['confidence']}")
    if r["missing_info"]:
        lines.append(f"НЕДОСТАЮЩАЯ ИНФО: {r['missing_info']}")
    if r["degradation_reasons"]:
        lines.append(f"ДЕГРАДАЦИИ: {r['degradation_reasons']}")
    if r["assumptions"]:
        lines.append(f"ДОПУЩЕНИЯ: {r['assumptions']}")
    lines.append(f"ИСПОЛЬЗОВАНА ИСТОРИЯ: {r['used_history']}")
    lines.append("")
    lines.append("ПОЛНЫЙ ТРЕЙС:")
    lines.append(json.dumps(r["trace"], indent=2, ensure_ascii=False))
    lines.append("")
    return "\n".join(lines)


def save_results(full_run: list) -> None:
    """Пишет results.txt рядом со скриптом со всеми запросами и полным трейсом."""
    total = len(full_run)
    if total == 0:
        print("⚠️  Нет результатов для сохранения в файл.")
        return

    chunks = [
        "RAG ASSISTANT TEST RESULTS\n",
        f"Всего запросов: {total}\n",
        f"{'#' * 70}\n",
    ]
    for idx, r in enumerate(full_run, start=1):
        chunks.append(format_result_for_file(r, idx, total))

    RESULTS_FILE.write_text("\n".join(chunks), encoding="utf-8")
    print(f"\n💾 Результаты сохранены в: {RESULTS_FILE}")

